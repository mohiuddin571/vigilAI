from enum import StrEnum


class ColorLabel(StrEnum):
    """A human-readable dominant-color label for a detected object."""

    RED = "red"
    ORANGE = "orange"
    YELLOW = "yellow"
    GREEN = "green"
    BLUE = "blue"
    PURPLE = "purple"
    BLACK = "black"
    WHITE = "white"
    GRAY = "gray"
    BROWN = "brown"
